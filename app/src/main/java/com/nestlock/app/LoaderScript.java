package com.nestlock.app;

import java.io.File;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

/**
 * Generates the root-side loader. It is invoked by GhostLock as
 * {@code $KSUD late-load --kmi ... --allow-shell}; the arguments are ignored
 * because the profile decides the actual insmod command.
 *
 * <p>The root script is started by the LKM's usermode helper and runs in
 * {@code u:r:kernel:s0}. That domain cannot read {@code /proc/modules} or
 * {@code pm}, and once the module re-enables enforcing it cannot exec any
 * userspace binary. Everything that needs userland therefore runs before the
 * insmod, and module success is taken from the {@code ksud insmod} exit code.
 *
 * <p>Manager activation: BakaSU (the default profile) is recognised by the
 * LKM's built-in BakaSU APK signature, so the kernel crowns
 * {@code com.resukisu.resukisu} on the manager's next launch without any
 * userspace registration. Profiles whose manager uses a different signature
 * still get a best-effort {@code registerCommand} run while the policy is
 * permissive; that command can fail when the kernel signature does not match.
 */
final class LoaderScript {
    private LoaderScript() {
    }

    static String generate(ManagerProfile profile, File lkm, File ksud, File status,
                           String managerApk) {
        Map<String, String> vars = new HashMap<>();
        vars.put("{ksud}", "\"$KSUD\"");
        vars.put("{lkm}", "\"$LKM\"");
        vars.put("{apk}", "\"$APK\"");

        StringBuilder s = new StringBuilder();
        s.append("#!/system/bin/sh\n");
        s.append("# Generated by NestLock. Profile: ").append(profile.id).append("\n");
        s.append("PATH=/system/bin:/system/xbin:/data/adb/ksu/bin\n");
        s.append("export PATH\n");
        s.append("STATUS=").append(Shell.quote(status.getAbsolutePath())).append("\n");
        s.append("KSUD_SRC=").append(Shell.quote(ksud.getAbsolutePath())).append("\n");
        s.append("KSUD_DST=").append(Shell.quote(profile.ksudPath)).append("\n");
        s.append("LKM=").append(Shell.quote(lkm.getAbsolutePath())).append("\n");
        s.append("MANAGER_PKG=").append(Shell.quote(profile.managerPackage)).append("\n");
        s.append("APK=").append(Shell.quote(managerApk == null ? "" : managerApk)).append("\n");
        s.append(": > \"$STATUS\" 2>/dev/null\n");
        s.append("chmod 644 \"$STATUS\" 2>/dev/null\n");
        s.append("status() { echo \"$*\" >> \"$STATUS\" 2>/dev/null; echo \"$*\"; }\n");
        s.append("fail() { status \"failed: $*\"; echo failed; exit 1; }\n");
        s.append("status \"start uid=$(id -u) euid=$(id -u)\"\n");
        s.append("status \"context=$(cat /proc/self/attr/current 2>/dev/null)\"\n");
        s.append("status \"manager apk=$APK\"\n");

        /* Everything that needs toybox runs while the policy is permissive. */
        s.append("KSUD_DIR=$(dirname \"$KSUD_DST\")\n");
        s.append("mkdir -p \"$KSUD_DIR\" 2>/dev/null || fail \"cannot create $KSUD_DIR\"\n");
        s.append("cp \"$KSUD_SRC\" \"$KSUD_DST\" || fail \"cannot copy ksud\"\n");
        s.append("chmod 755 \"$KSUD_DST\" || fail \"cannot chmod ksud\"\n");
        s.append("KSUD=\"$KSUD_DST\"\n");
        if (!profile.ksudLink.isEmpty()) {
            s.append("LINK_DIR=$(dirname ").append(Shell.quote(profile.ksudLink)).append(")\n");
            s.append("mkdir -p \"$LINK_DIR\" 2>/dev/null\n");
            s.append("ln -sf \"$KSUD_DST\" ").append(Shell.quote(profile.ksudLink))
                    .append(" 2>/dev/null || true\n");
        }

        /* The insmod is the module probe: its exit status is authoritative
         * because /proc/modules becomes unreadable afterwards. */
        s.append("status \"insmod start\"\n");
        s.append(Shell.renderCommand(profile.insmodArgs, vars)).append(" >> \"$STATUS\" 2>&1\n");
        s.append("INSMOD_RC=$?\n");
        s.append("status \"insmod rc=$INSMOD_RC\"\n");
        s.append("if [ \"$INSMOD_RC\" -ne 0 ]; then\n");
        s.append("  fail \"module missing\"\n");
        s.append("fi\n");
        s.append("status \"module loaded\"\n");
        s.append("status \"[+] KernelSU module loaded\"\n");

        /* Best-effort registration for managers without a built-in signature.
         * It runs while the driver may still be settling and cannot rely on
         * exec after the insmod re-enables enforcing. */
        if (profile.hasManager()) {
            List<String> registration = profile.effectiveRegisterCommand();
            if (!registration.isEmpty()) {
                s.append("if [ -n \"$APK\" ]; then\n");
                s.append("  ").append(Shell.renderCommand(registration, vars))
                        .append(" >> \"$STATUS\" 2>&1\n");
                s.append("  status \"register rc=$?\"\n");
                s.append("else\n");
                s.append("  status \"manager not installed: $MANAGER_PKG\"\n");
                s.append("fi\n");
            } else {
                s.append("status \"register skipped\"\n");
            }
        }

        s.append("ENF=\n");
        s.append("read -r ENF < /sys/fs/selinux/enforce 2>/dev/null\n");
        /* The app parser expects the word form. Write "Enforcing"/"Permissive"
         * (unknown reads fall back to the native log's enforce marker). */
        s.append("case \"$ENF\" in\n");
        s.append("  1) status \"enforce=Enforcing\" ;;\n");
        s.append("  0) status \"enforce=Permissive\" ;;\n");
        s.append("  *) status \"enforce=unknown\" ;;\n");
        s.append("esac\n");
        s.append("status \"done\"\n");
        s.append("exit 0\n");
        return s.toString();
    }
}
